// Package relaye2e is the crux verification for the relay box design: it
// proves that a real phone client can reach a real Mac companion process
// THROUGH a real relay box, end to end, while the box itself only ever
// handles ciphertext on the wire.
//
// It splices together two existing test rigs rather than reinventing them:
//   - the phone-side protocol client from
//     internal/mobileapi/transport/server_test.go (pairing.Service +
//     transport.Server + the real contract/pairing/session handshake), and
//   - the relay plumbing from internal/relayclient/harness_test.go (a real
//     relaybox.Box with a recording phone-door listener that captures every
//     byte the box handled).
//
// Nothing here reimplements pairing or session cryptography: every crypto
// step calls the exported pairing.* / contract.* functions the production
// code uses.
package relaye2e

